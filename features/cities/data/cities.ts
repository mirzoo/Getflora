export const cities = cityNames.map((name) => {
  const key = toCityKey(name);
  const coordinates = cityCoordinates[name];

  return {
    coordinates: coordinates
      ? {
          latitude: coordinates[0],
          longitude: coordinates[1],
        }
      : null,
    id: key,
    name,
    slug: key,
  };
});

export const featuredCities = cities.slice(0, featuredCityNames.length);

export const defaultCityName = "Санкт-Петербург";

function toCityKey(name: string) {
  return name
    .toLowerCase()
    .replaceAll("ё", "е")
    .replace(/[^a-zа-я0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}
